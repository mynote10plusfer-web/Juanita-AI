import java.util.Locale

/**
 * Debug-only helper: exposes the Firebase App Check debug secret generated by
 * the official Firebase debug provider. The secret remains in app-private
 * SharedPreferences and is never written to source code or logs by this app.
 */
@Composable
fun AppCheckDebugPanel() {
    val context = LocalContext.current
    var token by remember { mutableStateOf<String?>(null) }
    var message by remember { mutableStateOf("Il token viene creato dal provider Firebase all'avvio.") }
    val gold = Color(0xFFE4BD69)

    Card(
        modifier = Modifier.fillMaxWidth(),
        colors = CardDefaults.cardColors(containerColor = Color(0xFF17191D)),
        shape = RoundedCornerShape(20.dp)
    ) {
        Column(
            modifier = Modifier.padding(18.dp),
            verticalArrangement = Arrangement.spacedBy(10.dp)
        ) {
            Text("APP CHECK · DEBUG", color = gold, style = MaterialTheme.typography.titleSmall)
            Text(
                "Strumento temporaneo per leggere il token debug generato dal componente ufficiale Firebase. Non condividere questo codice.",
                color = Color(0xFFB9BBC1),
                style = MaterialTheme.typography.bodySmall
            )
            Button(
                onClick = {
                    try {
                        val app = FirebaseApp.getInstance()
                        val persistenceKey = app.getPersistenceKey()
                        val prefsName = String.format(
                            Locale.US,
                            "com.google.firebase.appcheck.debug.store.%s",
                            persistenceKey
                        )
                        val prefs = context.getSharedPreferences(prefsName, Context.MODE_PRIVATE)
                        token = prefs.getString(
                            "com.google.firebase.appcheck.debug.DEBUG_SECRET",
                            null
                        )
                        message = if (token.isNullOrBlank()) {
                            "Token non ancora creato. Avvia una conversazione Live, attendi qualche secondo e premi di nuovo."
                        } else {
                            "Token trovato. Registralo in Firebase Console → App Check → Gestisci token debug."
                        }
                    } catch (error: Exception) {
                        token = null
                        message = "Lettura non riuscita: ${error.localizedMessage ?: "errore sconosciuto"}"
                    }
                },
                modifier = Modifier.fillMaxWidth(),
                colors = ButtonDefaults.buttonColors(containerColor = gold, contentColor = Color.Black)
            ) {
                Text("Leggi token debug")
            }
            if (!token.isNullOrBlank()) {
                Text(token!!, color = Color.White, style = MaterialTheme.typography.bodyMedium)
                Button(
                    onClick = {
                        val clipboard = context.getSystemService(Context.CLIPBOARD_SERVICE) as ClipboardManager
                        clipboard.setPrimaryClip(ClipData.newPlainText("Firebase App Check debug token", token))
                        message = "Token copiato negli appunti. Non incollarlo in chat o repository pubblici."
                    },
                    modifier = Modifier.fillMaxWidth(),
                    colors = ButtonDefaults.buttonColors(containerColor = Color(0xFF30343B), contentColor = gold)
                ) {
                    Text("Copia token")
                }
            }
            Text(message, color = Color(0xFF9A9DA4), style = MaterialTheme.typography.bodySmall)
        }
    }
}
